// Migration script: MySQL → PostgreSQL (Neon)
// Reads all tables from MySQL, writes them to Neon.
// Idempotent: drops and recreates each table.
//
// Usage:
//   node migrate_to_neon.js
//
// Requires: .env for MySQL creds (DB_HOST, DB_USER, DB_PASSWORD, DB_NAME),
//           .env.pg for PostgreSQL creds (DB_HOST, DB_USER, DB_PASSWORD, DB_NAME, DB_PORT).

const mysql = require('mysql2/promise');
const { Client } = require('pg');
const fs = require('fs');
const path = require('path');

// --- Load MySQL env ---
require('dotenv').config({ path: path.join(__dirname, '.env') });

const MYSQL_CONFIG = {
  host: process.env.DB_HOST,
  user: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  database: process.env.DB_NAME,
};

// --- Load PostgreSQL env (do not use dotenv's override yet, to avoid clobbering) ---
const pgEnvPath = path.join(__dirname, '.env.pg');
if (!fs.existsSync(pgEnvPath)) {
  console.error('Missing .env.pg');
  process.exit(1);
}
const pgEnv = require('dotenv').parse(fs.readFileSync(pgEnvPath));

function escapeStr(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

// MySQL type → PostgreSQL type
function mapMySQLTypeToPostgres(mysqlType, nullable, columnDefault, extra, enumValues) {
  const t = mysqlType.toLowerCase();
  let pg = 'text';
  let isAutoIncrement = /auto_increment/i.test(extra || '');

  if (t.startsWith('tinyint(1)')) {
    pg = 'smallint'; // keep numeric to preserve existing === 1 checks
  } else if (t.startsWith('tinyint') || t.startsWith('smallint') || t.startsWith('mediumint') || t.startsWith('int')) {
    pg = 'integer';
  } else if (t.startsWith('bigint')) {
    pg = 'bigint';
  } else if (t.startsWith('decimal') || t.startsWith('numeric')) {
    const m = t.match(/\((\d+),(\d+)\)/);
    pg = m ? `numeric(${m[1]},${m[2]})` : 'numeric';
  } else if (t.startsWith('float')) {
    pg = 'real';
  } else if (t.startsWith('double')) {
    pg = 'double precision';
  } else if (t.startsWith('varchar')) {
    const m = t.match(/\((\d+)\)/);
    pg = m ? `varchar(${m[1]})` : 'text';
  } else if (t.startsWith('char')) {
    const m = t.match(/\((\d+)\)/);
    pg = m ? `char(${m[1]})` : 'char(1)';
  } else if (/^(tiny|medium|long)?text$/.test(t)) {
    pg = 'text';
  } else if (t.startsWith('datetime') || t.startsWith('timestamp')) {
    pg = 'timestamp';
  } else if (t.startsWith('date')) {
    pg = 'date';
  } else if (t.startsWith('time')) {
    pg = 'time';
  } else if (t.startsWith('enum')) {
    const inner = mysqlType.match(/^enum\((.*)\)$/i);
    if (inner) {
      const values = inner[1].split(',').map((s) => s.trim().replace(/^'|'$/g, ''));
      enumValues.push(...values);
      pg = `varchar(${Math.max(...values.map((v) => v.length), 1)})`;
    } else {
      pg = 'text';
    }
  } else if (t.startsWith('blob') || t.startsWith('binary') || t.startsWith('varbinary')) {
    pg = 'bytea';
  } else if (t.startsWith('json')) {
    pg = 'jsonb';
  }

  // Identity for AUTO_INCREMENT columns
  if (isAutoIncrement) {
    pg = pg.replace(/^(\w+(\(\d+(,\d+)?\))?)/, '$1 GENERATED BY DEFAULT AS IDENTITY');
  }

  // NOT NULL
  if (!nullable && !isAutoIncrement) {
    pg += ' NOT NULL';
  } else if (!nullable && isAutoIncrement) {
    // identity columns are implicitly NOT NULL
  }

  // DEFAULT CURRENT_TIMESTAMP for datetime/timestamp
  if (columnDefault !== null && columnDefault !== undefined) {
    const d = String(columnDefault);
    if (/^CURRENT_TIMESTAMP(\(\d+\))?$/i.test(d) || /^now\(\)$/i.test(d)) {
      pg += ' DEFAULT CURRENT_TIMESTAMP';
    } else if (pg.startsWith('numeric') || pg.startsWith('integer') || pg.startsWith('bigint') || pg.startsWith('smallint') || pg.startsWith('real') || pg.startsWith('double')) {
      pg += ` DEFAULT ${d}`;
    } else if (d === 'NULL') {
      // no default
    } else {
      pg += ` DEFAULT ${escapeStr(d)}`;
    }
  }

  return pg;
}

async function main() {
  const mysqlConn = await mysql.createConnection(MYSQL_CONFIG);
  console.log('Connected to MySQL');

  const pg = new Client({
    host: pgEnv.DB_HOST,
    user: pgEnv.DB_USER,
    password: pgEnv.DB_PASSWORD,
    database: pgEnv.DB_NAME,
    port: pgEnv.DB_PORT ? parseInt(pgEnv.DB_PORT) : 5432,
    ssl: { rejectUnauthorized: false },
  });
  await pg.connect();
  console.log('Connected to Neon');

  // Get all base tables from MySQL
  const [tables] = await mysqlConn.query('SHOW FULL TABLES');
  const tableNames = tables
    .filter((row) => Object.values(row)[1] === 'BASE TABLE')
    .map((row) => Object.values(row)[0]);
  console.log(`Found ${tableNames.length} base tables`);

  // Phase 1: tables
  for (const table of tableNames) {
    console.log(`\n--- Migrating table: ${table} ---`);

    const [rows] = await mysqlConn.query(`SELECT * FROM \`${table}\``);
    console.log(`  ${rows.length} rows`);

    const [columns] = await mysqlConn.query(`SHOW FULL COLUMNS FROM \`${table}\``);

    // Build column definitions
    const pgColumnDefs = columns.map((col) => {
      const enumValues = [];
      const def = mapMySQLTypeToPostgres(col.Type, col.Null === 'YES', col.Default, col.Extra, enumValues);
      let s = `"${col.Field}" ${def}`;
      if (enumValues.length > 0) {
        const list = enumValues.map(escapeStr).join(', ');
        s += ` CHECK ("${col.Field}" IN (${list}))`;
      }
      return s;
    });

    // Primary key(s) — use SHOW KEYS grouped by Key_name for composites
    const [keys] = await mysqlConn.query(`SHOW KEYS FROM \`${table}\``);
    const pkCols = keys
      .filter((k) => k.Key_name === 'PRIMARY')
      .sort((a, b) => a.Seq_in_index - b.Seq_in_index)
      .map((k) => `"${k.Column_name}"`);
    const pkClause = pkCols.length > 0 ? `, PRIMARY KEY (${pkCols.join(', ')})` : '';

    // Unique constraints (non-PK)
    const uniqueIndexes = {};
    keys.forEach((k) => {
      if (k.Key_name !== 'PRIMARY' && k.Non_unique === 0) {
        if (!uniqueIndexes[k.Key_name]) uniqueIndexes[k.Key_name] = [];
        uniqueIndexes[k.Key_name].push({ col: k.Column_name, seq: k.Seq_in_index });
      }
    });
    const uniqueClauses = Object.entries(uniqueIndexes).map(([name, cols]) => {
      const sorted = cols.sort((a, b) => a.seq - b.seq).map((c) => `"${c.col}"`);
      return `, UNIQUE (${sorted.join(', ')})`;
    });

    const dropSQL = `DROP TABLE IF EXISTS "${table}" CASCADE`;
    const createSQL = `CREATE TABLE "${table}" (${pgColumnDefs.join(', ')}${pkClause}${uniqueClauses.join('')})`;

    await pg.query(dropSQL);
    await pg.query(createSQL);
    console.log(`  Created table "${table}"`);

    // Regular (non-unique, non-PK) indexes
    const regIndexes = {};
    keys.forEach((k) => {
      if (k.Key_name !== 'PRIMARY' && k.Non_unique === 1) {
        if (!regIndexes[k.Key_name]) regIndexes[k.Key_name] = [];
        regIndexes[k.Key_name].push({ col: k.Column_name, seq: k.Seq_in_index });
      }
    });
    for (const [name, cols] of Object.entries(regIndexes)) {
      const sorted = cols.sort((a, b) => a.seq - b.seq).map((c) => `"${c.col}"`);
      await pg.query(`CREATE INDEX IF NOT EXISTS "${table}_${name}" ON "${table}" (${sorted.join(', ')})`);
    }

    // Insert rows
    if (rows.length > 0) {
      const colNames = columns.map((c) => `"${c.Field}"`).join(', ');
      const placeholders = columns.map((_, i) => `$${i + 1}`).join(', ');
      const insertSQL = `INSERT INTO "${table}" (${colNames}) VALUES (${placeholders})`;

      let inserted = 0;
      for (const row of rows) {
        const values = columns.map((c) => {
          let val = row[c.Field];
          if (val === null || val === undefined) return null;
          if (Buffer.isBuffer(val)) return val;
          if (val instanceof Date) return val;
          if (typeof val === 'string') {
            // Strip CR/LF that got baked in from Windows line endings in MySQL data
            return val.replace(/[\r\n]+/g, ' ').trim();
          }
          return val;
        });

        try {
          await pg.query(insertSQL, values);
          inserted++;
        } catch (err) {
          console.error(`  Row insert failed on ${table}: ${err.message}`);
          console.error('  Values:', values);
          throw err; // fail loud
        }
      }
      console.log(`  Inserted ${inserted}/${rows.length} rows`);

      // Bump the identity past the max id if the table has an identity column
      const idCol = columns.find((c) => /auto_increment/i.test(c.Extra || ''));
      if (idCol) {
        await pg.query(
          `SELECT setval(pg_get_serial_sequence('"${table}"', '${idCol.Field}'), COALESCE((SELECT MAX("${idCol.Field}") FROM "${table}"), 0) + 1, false)`
        );
      }
    }
  }

  // Phase 2: foreign keys (after all tables exist)
  console.log('\n--- Creating foreign keys ---');
  const [fks] = await mysqlConn.query(`
    SELECT TABLE_NAME, COLUMN_NAME, CONSTRAINT_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
    FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = ? AND REFERENCED_TABLE_NAME IS NOT NULL
    ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION
  `, [MYSQL_CONFIG.database]);

  const fkGroups = {};
  fks.forEach((fk) => {
    const key = `${fk.TABLE_NAME}.${fk.CONSTRAINT_NAME}`;
    if (!fkGroups[key]) fkGroups[key] = { table: fk.TABLE_NAME, cols: [], refTable: fk.REFERENCED_TABLE_NAME, refCols: [] };
    fkGroups[key].cols.push(`"${fk.COLUMN_NAME}"`);
    fkGroups[key].refCols.push(`"${fk.REFERENCED_COLUMN_NAME}"`);
  });

  for (const [key, fk] of Object.entries(fkGroups)) {
    const name = `fk_${key.replace(/\./g, '_')}`;
    const sql = `ALTER TABLE "${fk.table}" ADD CONSTRAINT "${name}" FOREIGN KEY (${fk.cols.join(', ')}) REFERENCES "${fk.refTable}" (${fk.refCols.join(', ')})`;
    try {
      await pg.query(sql);
      console.log(`  OK   ${name}`);
    } catch (err) {
      console.warn(`  WARN ${name} - ${err.message}`);
    }
  }

  await mysqlConn.end();
  await pg.end();
  console.log('\nMigration complete');
}

main().catch((err) => {
  console.error('Migration failed:', err);
  process.exit(1);
});